import Foundation

/// 聞き取りを一時停止・再開できる認識器の「差し込み口」。
///
/// たとえ話:ふつうの `SpeechRecognizing` は「ずっと起きているマイク」。
/// このプロトコルに対応した認識器は、さらに「今だけ耳をふさぐ・また聞き始める」ができる、
/// 一時的に耳栓ができるマイクのようなもの。
///
/// `TranslationPipeline` は、渡された認識器がこれにも対応していれば、
/// 自分の声を読み上げている間だけ実際に聞き取りを止め、読み上げが終わったら再開する。
/// 対応していない認識器を渡した場合は、これまでどおり
/// 「読み上げ中に届いた認識結果を無視する」という軽い対策のままになる。
public protocol PausableSpeechRecognizing: SpeechRecognizing {
    /// 聞き取りを一時停止する。マイクの音そのものは止めなくてよいが、
    /// 認識結果(`transcripts` から流れてくるもの)は止まっている間は増えないようにする。
    func pause() async
    /// 一時停止していた聞き取りを再開する。
    func resume() async
}
